## 5. 错题与复盘

以下内容是本日最需要回顾的几个点：

### 5.1 错点一：子类是否能直接访问父类 private 字段

错误认知：

- 之前容易以为“子类继承了父类一切成员”，忽略了 private 的限制。

正确理解：

- 子类继承的是“成员的定义和实现”，但不能直接访问 private 字段。
- 必须通过父类公开/受保护的方法来访问。

### 5.2 错点二：重载与重写混淆

错误认知：

- 容易将“参数不同的同名方法”误认为是方法重写。

正确理解：

- 重载是同一类中，同名方法参数不同
- 重写是子类覆盖父类方法

### 5.3 错点三：向下转型没有做判断

错误认知：

- 若直接强转，容易出现运行时异常。

正确理解：

- 强转前最好使用 instanceof
- 例如：if (obj instanceof Circle) {
    Circle c = (Circle) obj;
  }

