## 6. LeetCode 3 题复盘

### 6.1 题目理解

题目要求：

- 求一个字符串中，最长无重复字符子串的长度

例如：

- 输入："abcabcbb"
- 输出：3
- 原因："abc" 为最长无重复字符子串

### 6.2 核心思路

使用滑动窗口：

- left 表示窗口起点
- right 表示窗口终点
- 使用哈希表记录字符是否已在当前窗口中
- 遇到重复字符时，移动 left
- 每次更新最大长度

### 6.3 Java 实现要点

伪代码思路：

- 初始化 Map<Character, Integer> map
- 遍历字符串
- 如果当前字符已存在并且它在窗口中：更新 left
- 更新 map 中字符的最新位置
- 维护 maxLen

### 6.4 时间复杂度分析

- 访问每个字符最多一次
- 每次更新 left 和 map 仅常数时间

所以整体复杂度为：

- 时间复杂度：O(n)
- 空间复杂度：O(min(n, charset))

