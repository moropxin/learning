## 1. 本日学习目标

-- 封装-继承-多态
- • 封装（Encapsulation）
  • 含义：把数据（字段）和对数据的操作（方法）放在一起，使用访问权限（private/protected/public）控制外部访问。
  • 关键点：用 getter/setter 控制读写；封装是为了隐藏实现细节并保证不被任意篡改。
  
- • 继承（Inheritance）
  • 含义：子类继承父类的属性和方法，重用代码。
  • 关键点：is-a 关系；注意构造器调用顺序（super）；protected 的作用。
  
- • 多态（Polymorphism）
  • 含义：同一接口或父类型引用在运行时表现出不同的实现（方法重写）。
  • 关键点：编译时看引用类型，运行时看对象类型；重写（override） vs 重载（overload）。
  
• 接口 vs 抽象类
  • 接口适用：纯行为规范，可多继承（Java 8+ 有 default/static 方法）。
  • 抽象类适用：有共用实现或状态，单继承限制下用抽象类。

