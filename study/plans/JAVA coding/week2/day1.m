## 3. 核心知识点回顾

### 3.1 封装

封装的核心思想是：把“数据”和“操作数据的方法”放在一起，并对外隐藏实现细节。

常见例子：

- 使用 private 修饰字段
- 通过 getter 和 setter 对外暴露访问接口
- 在 setter 中检查有效性，例如 age >= 0 && age <= 150

优点：

- 增强代码安全性
- 降低耦合度
- 便于后续维护和扩展

关键理解：

- private 只能在当前类中使用
- 子类不能直接访问父类的 private 成员
- 但子类可以通过父类提供的 public / protected 方法间接访问

### 3.2 继承

继承的本质是：让子类复用父类中的属性和方法，形成“is-a”的关系。

典型理解点：

- 子类继承父类的非 private 成员
- 当创建子类对象时，父类构造器会先被调用
- 子类可以扩展父类功能，也可重写方法

常见容易混淆的点：

- private 不是“不可继承”，而是“不能直接访问”
- 继承不是复制代码，而是复用父类的逻辑结构

### 3.3 多态

多态的核心是：同一个方法调用会根据对象实际类型执行不同的实现。

例如：

- 父类引用指向子类对象
- 调用父类方法时，实际执行的是子类覆盖后的方法

常见场景：

- 抽象类与接口的实现类
- 数组/集合中存储父类对象，而实际运行时对象不同

关键概念：

- 重载（overload）：同一个类中，参数列表不同的方法
- 重写（override）：子类覆盖父类方法
- 动态绑定：运行时决定调用哪个实现

### 3.4 访问控制与可见性

Java 中常用权限修饰符：

- public：任何类都可以访问
- protected：同包下或子类中可访问
- 默认（包级）访问：同包可见
- private：仅当前类可访问

日常使用建议：

- 字段尽量用 private
- 需要复用给子类时，可考虑 protected
- 对外提供接口时再用 public

